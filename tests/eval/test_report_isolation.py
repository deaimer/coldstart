def test_report_regeneration_is_idempotent(fake_repo):
    config = make_config(trials_per_task=3, estimated_cost_per_trial_usd=0.1)
    trial_ids = _plan_trial_ids(fake_repo, config)
    script = {tid: [ScriptedOutcome(kind="passed", cost_usd=0.1)] for tid in trial_ids}
    _run(fake_repo, config, script, run_id="idempotent-report-run")

    first = orchestrator.regenerate_reports(
        "idempotent-report-run",
        repo_root=fake_repo,
        coldstart_dir=fake_repo / COLDSTART,
        phase1_db_path=fake_repo / COLDSTART / "results.db",
    )
    second = orchestrator.regenerate_reports(
        "idempotent-report-run",
        repo_root=fake_repo,
        coldstart_dir=fake_repo / COLDSTART,
        phase1_db_path=fake_repo / COLDSTART / "results.db",
    )
    assert first.private_report.path == second.private_report.path
    assert first.public_report.path == second.public_report.path

    report1 = _read_public_report(fake_repo, "idempotent-report-run")
    report2 = _read_public_report(fake_repo, "idempotent-report-run")
    for key in ("attempts", "scored_attempts", "strict_pass_rate", "cost", "runtime", "dimension_averages"):
        assert report1[key] == report2[key]


def test_regenerate_reports_does_not_execute_harbor_and_matches_smoke_scenario(fake_repo):
    """Simulates the exact reported smoke-run defect end to end: a
    pre-existing five-trial baseline plus one new orchestration run sharing
    the same task/system, then `regenerate-reports` (no Harbor call) must
    reproduce a one-attempt report."""
    baseline_config = make_config(id="baseline", trials_per_task=5, estimated_cost_per_trial_usd=0.1)
    baseline_ids = _plan_trial_ids(fake_repo, baseline_config)
    _run(
        fake_repo,
        baseline_config,
        {tid: [ScriptedOutcome(kind="passed", cost_usd=0.1)] for tid in baseline_ids},
        run_id="baseline-run",
    )

    smoke_config = make_config(id="smoke", trials_per_task=1, estimated_cost_per_trial_usd=0.3162636)
    smoke_ids = _plan_trial_ids(fake_repo, smoke_config)
    _run(
        fake_repo,
        smoke_config,
        {smoke_ids[0]: [ScriptedOutcome(kind="failed", cost_usd=0.3162636)]},
        run_id="smoke-run",
    )

    outcome = orchestrator.regenerate_reports(
        "smoke-run",
        repo_root=fake_repo,
        coldstart_dir=fake_repo / COLDSTART,
        phase1_db_path=fake_repo / COLDSTART / "results.db",
    )
    assert outcome.public_report.generated
    report = _read_public_report(fake_repo, "smoke-run")
    assert report["attempts"] == 1
    assert report["orchestration_run_id"] == "smoke-run"


def test_resume_preserves_trial_key_membership(fake_repo):
    config = make_config(trials_per_task=3, max_budget_usd=5.0, estimated_cost_per_trial_usd=0.1)
    trial_ids = _plan_trial_ids(fake_repo, config)

    class InterruptOnce(FakeHarborRunner):
        def __init__(self, script):
            super().__init__(script)
            self._n = 0

        def run_trial(self, *, trial, job_name, jobs_dir, on_progress=None):
            self._n += 1
            if self._n == 2:
                raise KeyboardInterrupt()
            return super().run_trial(trial=trial, job_name=job_name, jobs_dir=jobs_dir, on_progress=on_progress)

    coldstart_dir = fake_repo / COLDSTART
    script = {tid: [ScriptedOutcome(kind="passed", cost_usd=0.1)] for tid in trial_ids}
    with pytest.raises(orchestrator.RunInterrupted):
        orchestrator.run_evaluation(
            config,
            repo_root=fake_repo,
            coldstart_dir=coldstart_dir,
            phase1_db_path=coldstart_dir / "results.db",
            allow_dirty=False,
            budget_ack=False,
            harbor_runner=InterruptOnce(script),
            run_id="resume-membership-run",
            skip_preflight=True,
        )

    first_trial_key = manifest_module.read_state(
        manifest_module.run_dir_for(coldstart_dir, "resume-membership-run")
    ).trials[trial_ids[0]].phase1_trial_key
    assert first_trial_key is not None

    resume_script = {tid: [ScriptedOutcome(kind="passed", cost_usd=0.1)] for tid in trial_ids[1:]}
    outcome = orchestrator.resume_evaluation(
        "resume-membership-run",
        config,
        repo_root=fake_repo,
        coldstart_dir=coldstart_dir,
        phase1_db_path=coldstart_dir / "results.db",
        budget_ack=False,
        harbor_runner=FakeHarborRunner(resume_script),
        skip_preflight=True,
    )
    assert outcome.state.status == "completed"
    # The membership recorded before the interruption must still be present
    # and must still be exactly what the (now-completed) report reflects.
    assert outcome.state.trials[trial_ids[0]].phase1_trial_key == first_trial_key
    report = _read_public_report(fake_repo, "resume-membership-run")
    assert report["attempts"] == 3


