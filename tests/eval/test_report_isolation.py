"""Phase 2.1: report isolation.

Automatic reports generated by `eval run`/`eval resume`/
`eval regenerate-reports` must be scoped to exactly the trials belonging to
that orchestration run, never inferred from task/system identity alone --
even when other, unrelated trials for the very same (task, system) pair
already exist in the Phase 1 store.
"""

from __future__ import annotations

import json

import pytest

from coldctl.eval import manifest as manifest_module
from coldctl.eval import orchestrator
from coldctl.eval.planner import build_plan
from coldctl.results import db as db_module
from coldctl.results.aggregate import (
    EmptyTrialSelectionError,
    UnknownTrialKeysError,
    compute_aggregate,
    compute_aggregate_for_trial_keys,
)

from .conftest import make_config
from .fake_harbor import FakeHarborRunner, ScriptedOutcome

COLDSTART = ".coldstart"


def _plan_trial_ids(fake_repo, config):
    plan = build_plan(config, repo_root=fake_repo, phase1_db_path=fake_repo / COLDSTART / "results.db", allow_dirty=False)
    return [t.trial_id for t in plan.trials]


def _run(fake_repo, config, script, *, run_id):
    coldstart_dir = fake_repo / COLDSTART
    outcome = orchestrator.run_evaluation(
        config,
        repo_root=fake_repo,
        coldstart_dir=coldstart_dir,
        phase1_db_path=coldstart_dir / "results.db",
        allow_dirty=False,
        budget_ack=False,
        harbor_runner=FakeHarborRunner(script),
        run_id=run_id,
        skip_preflight=True,
    )
    return outcome


def _read_public_report(fake_repo, run_id):
    directory = fake_repo / "reports" / "generated" / run_id
    files = list(directory.glob("*.public.json"))
    assert len(files) == 1, f"expected exactly one public report in {directory}, found {files}"
    return json.loads(files[0].read_text())


def _read_private_report(fake_repo, run_id):
    directory = fake_repo / ".coldstart" / "private-reports" / run_id
    files = list(directory.glob("*.private.json"))
    assert len(files) == 1
    return json.loads(files[0].read_text())


def test_two_orchestration_runs_sharing_task_system_remain_isolated(fake_repo):
    """Two separate five-trial runs against the same (task, system) pair
    must each report only their own five trials -- ten total in the store,
    five each in the reports."""
    config_a = make_config(id="group-a", trials_per_task=5, estimated_cost_per_trial_usd=0.1)
    trial_ids_a = _plan_trial_ids(fake_repo, config_a)
    script_a = {tid: [ScriptedOutcome(kind="passed", cost_usd=0.1)] for tid in trial_ids_a}
    outcome_a = _run(fake_repo, config_a, script_a, run_id="group-a-run")

    config_b = make_config(id="group-b", trials_per_task=5, estimated_cost_per_trial_usd=0.2)
    trial_ids_b = _plan_trial_ids(fake_repo, config_b)
    script_b = {tid: [ScriptedOutcome(kind="passed", cost_usd=0.2)] for tid in trial_ids_b}
    outcome_b = _run(fake_repo, config_b, script_b, run_id="group-b-run")

    # Both groups landed in the very same (task, system) pair in Phase 1.
    conn = db_module.connect(fake_repo / COLDSTART / "results.db")
    try:
        all_history = compute_aggregate(conn, task="fake-task", system="gpt-5.6-terra__terminus-2")
    finally:
        conn.close()
    assert all_history.attempts == 10

    report_a = _read_public_report(fake_repo, "group-a-run")
    report_b = _read_public_report(fake_repo, "group-b-run")

    assert report_a["attempts"] == 5
    assert report_b["attempts"] == 5
    assert report_a["cost"]["total_usd"] == pytest.approx(0.5)
    assert report_b["cost"]["total_usd"] == pytest.approx(1.0)
    assert report_a["orchestration_run_id"] == "group-a-run"
    assert report_b["orchestration_run_id"] == "group-b-run"


def test_one_trial_report_does_not_include_five_previous_trials(fake_repo):
    """Reproduces the originally-reported defect scenario directly: a
    five-trial baseline followed by a single new orchestration run against
    the same (task, system) -- the new run's report must show exactly 1
    attempt, not 6."""
    baseline_config = make_config(id="baseline", trials_per_task=5, estimated_cost_per_trial_usd=0.1)
    baseline_ids = _plan_trial_ids(fake_repo, baseline_config)
    baseline_script = {tid: [ScriptedOutcome(kind="passed", cost_usd=0.1)] for tid in baseline_ids}
    _run(fake_repo, baseline_config, baseline_script, run_id="baseline-run")

    smoke_config = make_config(id="smoke", trials_per_task=1, estimated_cost_per_trial_usd=0.3162636)
    smoke_ids = _plan_trial_ids(fake_repo, smoke_config)
    smoke_script = {smoke_ids[0]: [ScriptedOutcome(kind="failed", cost_usd=0.3162636)]}
    _run(fake_repo, smoke_config, smoke_script, run_id="smoke-run")

    report = _read_public_report(fake_repo, "smoke-run")
    assert report["attempts"] == 1
    assert report["scored_attempts"] == 1
    assert report["cost"]["total_usd"] == pytest.approx(0.3162636)
    assert report["failure_totals"]["failures"] == 1


def test_explicit_five_trial_selection_still_produces_original_baseline(fake_repo):
    baseline_config = make_config(id="baseline", trials_per_task=5, estimated_cost_per_trial_usd=0.1)
    baseline_ids = _plan_trial_ids(fake_repo, baseline_config)
    costs = [0.36537539999999996, 0.3143266, 0.34395070000000005, 0.22094049999999998, 0.2327576]
    rewards_list = [
        {"coldstart_pass": 0.0, "functional": 1.0, "durability": 1.0, "evidence": 1.0, "integrity": 1.0, "state_safety": 0.6666666666666666},
        {"coldstart_pass": 0.0, "functional": 1.0, "durability": 1.0, "evidence": 1.0, "integrity": 0.5, "state_safety": 0.6666666666666666},
        {"coldstart_pass": 1.0, "functional": 1.0, "durability": 1.0, "evidence": 1.0, "integrity": 1.0, "state_safety": 1.0},
        {"coldstart_pass": 0.0, "functional": 0.5, "durability": 0.0, "evidence": 0.0, "integrity": 0.0, "state_safety": 0.6666666666666666},
        {"coldstart_pass": 0.0, "functional": 1.0, "durability": 1.0, "evidence": 1.0, "integrity": 0.5, "state_safety": 0.6666666666666666},
    ]
    baseline_script = {
        tid: [ScriptedOutcome(kind="passed" if rewards_list[i]["coldstart_pass"] >= 1.0 else "failed", cost_usd=costs[i], rewards=rewards_list[i])]
        for i, tid in enumerate(baseline_ids)
    }
    outcome = _run(fake_repo, baseline_config, baseline_script, run_id="baseline-run")

    # An unrelated sixth trial in the same (task, system) pair.
    extra_config = make_config(id="extra", trials_per_task=1, estimated_cost_per_trial_usd=0.5)
    extra_ids = _plan_trial_ids(fake_repo, extra_config)
    _run(fake_repo, extra_config, {extra_ids[0]: [ScriptedOutcome(kind="passed", cost_usd=0.5)]}, run_id="extra-run")

    baseline_trial_keys = [
        outcome.state.trials[tid].phase1_trial_key for tid in baseline_ids
    ]
    assert all(baseline_trial_keys)

    conn = db_module.connect(fake_repo / COLDSTART / "results.db")
    try:
        agg = compute_aggregate_for_trial_keys(
            conn, baseline_trial_keys, task="fake-task", system="gpt-5.6-terra__terminus-2"
        )
        all_history = compute_aggregate(conn, task="fake-task", system="gpt-5.6-terra__terminus-2")
    finally:
        conn.close()

    assert agg.attempts == 5
    assert agg.passes == 1
    assert agg.strict_pass_rate == 0.20
    assert agg.total_cost_usd == pytest.approx(1.4773508)
    # Sanity: all-history sees the extra trial too, proving isolation is real.
    assert all_history.attempts == 6


